#!/usr/bin/env python3
"""Run both language SDKs against an isolated real Beep Grid HTTP server."""
import contextlib
import os
import pathlib
import secrets
import subprocess
import time
import urllib.request

root = pathlib.Path(__file__).resolve().parents[1]
schema = "sdk_test_" + secrets.token_hex(8)
environment = dict(os.environ)
environment.update(NOTIF_ADDR="127.0.0.1:4011", NOTIF_PUBLIC_URL="http://localhost:4011",
                   NOTIF_SCHEMA=schema, NOTIF_WORKSPACE="sdk-tests",
                   NOTIF_BOOTSTRAP_TOKEN=secrets.token_hex(32), NOTIF_SECRET_KEY=secrets.token_hex(32))
database = environment.get("NOTIF_TEST_DATABASE_URL", "postgres://notif:notif@localhost:5499/notif?sslmode=disable")
environment["NOTIF_DATABASE_URL"] = database
environment["NOTIF_SDK_TEST_URL"] = "http://localhost:4011"
environment["NOTIF_SDK_TEST_TOKEN"] = environment["NOTIF_BOOTSTRAP_TOKEN"]
environment["PYTHONPATH"] = str(root / "sdk/python")
binary = root / ".local/notif-sdk-test"
binary.parent.mkdir(mode=0o700, exist_ok=True)
subprocess.run(["go", "build", "-buildvcs=false", "-o", str(binary), "./cmd/notif"], cwd=root, check=True)
subprocess.run([str(binary), "migrate"], cwd=root, env=environment, check=True)
server = subprocess.Popen([str(binary), "serve"], cwd=root, env=environment, stdout=subprocess.DEVNULL,
                          stderr=subprocess.DEVNULL)
try:
    for _ in range(100):
        try:
            with urllib.request.urlopen("http://localhost:4011/readyz", timeout=1) as response:
                if response.status == 200:
                    break
        except OSError:
            if server.poll() is not None:
                raise RuntimeError("SDK test server exited before readiness")
            time.sleep(.1)
    else:
        raise RuntimeError("SDK test server did not become ready")
    subprocess.run(["npm", "--prefix", "sdk/typescript", "test"], cwd=root, env=environment, check=True)
    subprocess.run(["python3", "-m", "unittest", "discover", "-s", "sdk/python/tests", "-v"], cwd=root,
                   env=environment, check=True)
finally:
    server.terminate()
    try:
        server.wait(timeout=10)
    except subprocess.TimeoutExpired:
        server.kill()
        server.wait()
    # schema was generated by this test invocation and never contains user data.
    subprocess.run(["psql", database, "-v", "ON_ERROR_STOP=1", "-c", f"DROP SCHEMA IF EXISTS {schema} CASCADE"],
                   cwd=root, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
