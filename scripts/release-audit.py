#!/usr/bin/env python3
"""Review tracked release files for accidental credentials and generate dependency license notices."""
import json
import os
import pathlib
import re
import subprocess

root = pathlib.Path(__file__).resolve().parents[1]
local_git = '/Library/Developer/CommandLineTools/usr/bin/git'
git = os.environ.get('NOTIF_GIT', local_git if pathlib.Path(local_git).exists() else 'git')
tracked = subprocess.check_output([git, 'ls-files', '-z'], cwd=root).decode().split('\0')
patterns = [re.compile(rb'ntf_[0-9a-f]{32}_[0-9a-f]{32}'),
            re.compile(rb'(?:sk-proj-|xoxb-)[A-Za-z0-9_-]{35,}'),
            re.compile(rb'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----')]
errors = []
for name in tracked:
    if not name or name.endswith(('package-lock.json', 'go.sum')):
        continue
    path = root / name
    if not path.is_file():
        continue
    raw = path.read_bytes()
    if any(p.search(raw) for p in patterns):
        errors.append(name)
if errors:
    raise SystemExit('Credential-like material requires review in: ' + ', '.join(errors))

raw = subprocess.check_output(['go', 'list', '-m', '-json', 'all'], cwd=root).decode()
decoder = json.JSONDecoder()
modules = []
while raw.strip():
    value, consumed = decoder.raw_decode(raw.lstrip())
    modules.append(value)
    raw = raw.lstrip()[consumed:]
notices = ['# Third party notices\n\nGenerated by scripts/release-audit.py. Runtime dependencies retain their licenses.\n']
for module in modules:
    if module.get('Main'):
        continue
    directory = pathlib.Path(module.get('Dir', ''))
    files = [p for p in directory.iterdir() if p.is_file() and p.name.upper() in ('LICENSE', 'LICENSE.TXT', 'COPYING', 'NOTICE')]
    if not files:
        raise SystemExit('License missing for ' + module['Path'])
    notices.append('\n## ' + module['Path'] + ' ' + module.get('Version', '') + '\n')
    for path in sorted(files):
        notices.append('\n' + path.read_text(errors='replace') + '\n')
goroot = pathlib.Path(subprocess.check_output(['go', 'env', 'GOROOT'], cwd=root).decode().strip())
notices.append('\n## Go standard library\n\n' + (goroot / 'LICENSE').read_text() + '\n')
for name in ('react', 'react-dom', 'scheduler', '@tanstack/react-query', '@tanstack/query-core', 'vite'):
    directory = root / 'workspace/node_modules' / name
    package = json.loads((directory / 'package.json').read_text())
    license_file = next((p for p in directory.iterdir() if p.name.upper().startswith('LICENSE')), None)
    if not license_file:
        raise SystemExit('License missing for ' + name)
    notices.append('\n## ' + name + ' ' + package['version'] + '\n\n' + license_file.read_text() + '\n')
(root / 'THIRD_PARTY_NOTICES.txt').write_text('\n'.join(line.rstrip() for line in ''.join(notices).rstrip().splitlines())+'\n')
print('Tracked-file credential scan passed; dependency license notices generated.')
